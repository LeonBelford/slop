"""Module cards: a compact, always-current description of every Python module for small models (and humans).

A card has the module's purpose (first docstring line), its public classes/functions with signatures and one-line docs, and who
imports it. `make cards` writes them to docs/MODULES.md; self-improve builds the cards of the files it is about to change live, so
the prompt never depends on a stale file. Standard library only.
"""
from __future__ import annotations

import ast
from pathlib import Path

SKIP = {".venv", ".venv-lint", "node_modules", "projects", "self_improve", "__pycache__", ".git", "bench"}


def modules(repo: Path) -> list[str]:
    repo = Path(repo)
    return sorted(str(p.relative_to(repo)) for p in repo.rglob("*.py")
                  if not SKIP & set(p.relative_to(repo).parts[:-1]) and not p.relative_to(repo).parts[0] == "tests")


def _sig(n: ast.AST) -> str:
    a = n.args
    names = [x.arg for x in [*a.posonlyargs, *a.args]]
    if a.vararg:
        names.append("*" + a.vararg.arg)
    names += [x.arg for x in a.kwonlyargs]
    if a.kwarg:
        names.append("**" + a.kwarg.arg)
    return f"{n.name}({', '.join(names)})"


def _doc(n: ast.AST) -> str:
    d = ast.get_docstring(n) or ""
    return d.strip().splitlines()[0][:110] if d.strip() else ""


def _imports(tree: ast.AST) -> set[str]:
    out = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            out |= {a.name.split(".")[-1] for a in n.names}
        elif isinstance(n, ast.ImportFrom):
            out |= {(n.module or "").split(".")[-1]} | {a.name for a in n.names}
    return out


def parse(repo: Path, files: list[str] | None = None) -> dict[str, dict]:
    repo = Path(repo)
    info: dict[str, dict] = {}
    for f in files or modules(repo):
        try:
            tree = ast.parse((repo / f).read_text("utf-8", "replace"))
        except (OSError, SyntaxError):
            continue
        items = []
        for n in tree.body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)) and not n.name.startswith("_"):
                items.append(f"def {_sig(n)}" + (f": {_doc(n)}" if _doc(n) else ""))
            elif isinstance(n, ast.ClassDef) and not n.name.startswith("_"):
                items.append(f"class {n.name}" + (f": {_doc(n)}" if _doc(n) else ""))
                items += [f"  .{_sig(m)}" for m in n.body if isinstance(m, ast.FunctionDef) and not m.name.startswith("_")][:12]
        info[f] = {"doc": _doc(tree), "items": items, "imports": _imports(tree), "lines": (repo / f).read_text("utf-8", "replace").count("\n") + 1}
    return info


def render(repo: Path, files: list[str] | None = None, max_items: int = 25) -> str:
    """Cards for `files` (default: all modules), each with the modules that import it."""
    info = parse(repo, None)
    shown = [f for f in (files or info) if f in info]
    lines = []
    for f in shown:
        stem = Path(f).stem
        users = sorted(g for g, d in info.items() if g != f and stem in d["imports"])
        lines.append(f"### {f} ({info[f]['lines']} lines)")
        lines.append(info[f]["doc"] or "(no description)")
        lines += [f"- {i}" for i in info[f]["items"][:max_items]]
        if len(info[f]["items"]) > max_items:
            lines.append(f"- ... {len(info[f]['items']) - max_items} more")
        lines.append("Used by: " + (", ".join(users[:12]) + (" ..." if len(users) > 12 else "") if users else "-"))
        lines.append("")
    return "\n".join(lines)


def write(repo: Path) -> Path:
    out = Path(repo) / "docs" / "MODULES.md"
    out.write_text("# Module cards\n\nGenerated by `make cards` (dash/modcards.py). Do not edit by hand; self-improve builds fresh cards "
                   "for the files it changes.\n\n" + render(repo), "utf-8")
    return out


if __name__ == "__main__":
    print(write(Path(__file__).resolve().parent.parent))
